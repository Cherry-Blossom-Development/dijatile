#!/usr/bin/env python3
"""Export Tilepet art from Aseprite into a C header (spec 7.2).

Each .aseprite file holds one layer set (a body build for a stage, or an
overlay such as "horns_curved"). Animations are Aseprite tags named after the
Anim list in lib/Pet/src/Art.h (idle, walk, run, ... eggcrack). Anchors are
Aseprite slices named head, eyes, mouth, tail, hand_l, hand_r, foot_l,
foot_r, keyed per frame; the slice centre is the anchor.

Colour mode must be Indexed, and palette indexes ARE the semantic slots:
  0 transparent, 1 outline, 2-4 body ramp (dark..light), 5-6 belly/markings,
  7-9 hair ramp, 10-11 horn/claw, 12-13 eyes, 14 blush, 15 highlight.
The genome recolours slots at run time, so draw every pet with the default
palette and keep to those indexes.

Usage:
  tools/sprites.py art/adult_normal.aseprite [more.aseprite ...] -o lib/Pet/src/pet_sprites.h
  tools/sprites.py --from-json sheet.json sheet.png -o out.h   # already exported

Needs the aseprite CLI on PATH (or --aseprite PATH) and Pillow.
The game still draws placeholder art in code (Art.cpp); the art pass will add
an ArtSource that reads this header instead.
"""

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile

ANIMS = [
    "idle", "walk", "run", "crawl", "climb", "tumble", "land", "sit", "sleep", "yawn", "eat", "play",
    "stumble", "shiver", "wave", "poop", "celebrate", "sadsit", "dangle", "point", "kick", "headshake",
    "scared", "flinch", "listen", "clap", "foottap", "bob", "sidestep", "hop", "spin", "armwave",
    "headbang", "wiggle", "twirl", "stomp", "shimmy", "swing", "bigfinish", "sway", "eggidle",
    "eggwobble", "eggcrack",
]
ANCHORS = ["head", "eyes", "mouth", "tail", "hand_l", "hand_r", "foot_l", "foot_r"]


def ident(s):
    return re.sub(r"[^a-zA-Z0-9]", "_", s).lower()


def export_with_aseprite(aseprite, src, tmp):
    base = os.path.join(tmp, ident(os.path.splitext(os.path.basename(src))[0]))
    png, js = base + ".png", base + ".json"
    subprocess.run(
        [aseprite, "-b", src, "--sheet", png, "--data", js, "--format", "json-array",
         "--list-tags", "--list-slices", "--sheet-type", "rows"],
        check=True,
    )
    return js, png


def load_sheet(js_path, png_path):
    from PIL import Image  # Pillow

    with open(js_path) as f:
        data = json.load(f)
    img = Image.open(png_path)
    if img.mode != "P":
        sys.exit(f"{png_path}: sprite must be in Indexed colour mode (palette slots)")
    return data, img


def frame_pixels(img, rect):
    x, y, w, h = rect["x"], rect["y"], rect["w"], rect["h"]
    px = img.crop((x, y, x + w, y + h)).load()
    out = []
    for yy in range(h):
        for xx in range(w):
            v = px[xx, yy]
            if v > 15:
                sys.exit(f"palette index {v} at {xx},{yy}: only slots 0..15 are allowed")
            out.append(v)
    return w, h, out


def pack4(pixels):
    out = bytearray()
    for i in range(0, len(pixels), 2):
        hi = pixels[i]
        lo = pixels[i + 1] if i + 1 < len(pixels) else 0
        out.append((hi << 4) | lo)
    return out


def anchors_for(data, frame_index):
    found = {}
    for sl in data.get("meta", {}).get("slices", []):
        name = sl["name"].lower()
        if name not in ANCHORS:
            continue
        key = None
        for k in sl.get("keys", []):
            if k["frame"] <= frame_index:
                key = k
        if key:
            b = key["bounds"]
            found[name] = (b["x"] + b["w"] // 2, b["y"] + b["h"] // 2)
    return [found.get(a, (-1, -1)) for a in ANCHORS]


def emit(sets, out):
    lines = [
        "#pragma once",
        "// Generated by tools/sprites.py. Do not edit.",
        "// 4 bpp frames (two pixels per byte, high nibble first), palette slots as in Art.h.",
        "",
        "#include <stdint.h>",
        "",
        "namespace pet {",
        "namespace sprites {",
        "",
        "struct Frame {",
        "  const uint8_t *data;",
        "  uint8_t w, h;",
        "  int8_t anchor[8][2];  // head, eyes, mouth, tail, hand_l, hand_r, foot_l, foot_r; -1 = none",
        "};",
        "struct AnimFrames {",
        "  const char *name;",
        "  const Frame *frames;",
        "  uint8_t count;",
        "};",
        "struct Set {",
        "  const char *name;",
        "  const AnimFrames *anims;",
        "  uint8_t count;",
        "};",
        "",
    ]
    set_names = []
    for set_name, anims in sets:
        sid = ident(set_name)
        set_names.append((set_name, sid))
        anim_entries = []
        for anim, frames in anims:
            aid = f"{sid}_{ident(anim)}"
            frame_entries = []
            for i, (w, h, packed, anchors) in enumerate(frames):
                lines.append(f"static const uint8_t {aid}_{i}[] = {{")
                for j in range(0, len(packed), 24):
                    lines.append("  " + ", ".join(f"0x{b:02x}" for b in packed[j:j + 24]) + ",")
                lines.append("};")
                anc = ", ".join(f"{{{x}, {y}}}" for x, y in anchors)
                frame_entries.append(f"  {{{aid}_{i}, {w}, {h}, {{{anc}}}}},")
            lines.append(f"static const Frame {aid}_frames[] = {{")
            lines.extend(frame_entries)
            lines.append("};")
            anim_entries.append(f'  {{"{anim}", {aid}_frames, {len(frames)}}},')
        lines.append(f"static const AnimFrames {sid}_anims[] = {{")
        lines.extend(anim_entries)
        lines.append("};")
        lines.append("")
    lines.append("static const Set SETS[] = {")
    for name, sid in set_names:
        lines.append(f'  {{"{name}", {sid}_anims, (uint8_t)(sizeof({sid}_anims) / sizeof({sid}_anims[0]))}},')
    lines.append("};")
    lines.append("constexpr int SET_COUNT = sizeof(SETS) / sizeof(SETS[0]);")
    lines.append("")
    lines.append("}  // namespace sprites")
    lines.append("}  // namespace pet")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


def convert(name, data, img):
    frames = data["frames"]
    tags = data.get("meta", {}).get("frameTags", [])
    if not tags:
        sys.exit(f"{name}: no tags (one tag per animation, named as in Art.h)")
    anims = []
    for tag in tags:
        anim = tag["name"].lower()
        if anim not in ANIMS:
            print(f"warning: {name}: tag '{anim}' is not in the Anim list; exported anyway", file=sys.stderr)
        out = []
        for fi in range(tag["from"], tag["to"] + 1):
            w, h, px = frame_pixels(img, frames[fi]["frame"])
            out.append((w, h, pack4(px), anchors_for(data, fi)))
        anims.append((anim, out))
    missing = [a for a in ANIMS if a not in {t for t, _ in anims}]
    if missing:
        print(f"note: {name}: no art yet for {', '.join(missing)}", file=sys.stderr)
    return anims


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("inputs", nargs="*", help=".aseprite files")
    ap.add_argument("--from-json", nargs=2, metavar=("JSON", "PNG"), help="use an existing sheet export")
    ap.add_argument("--aseprite", default="aseprite", help="path to the aseprite binary")
    ap.add_argument("-o", "--out", required=True, help="header to write")
    args = ap.parse_args()

    sets = []
    if args.from_json:
        data, img = load_sheet(*args.from_json)
        sets.append((os.path.splitext(os.path.basename(args.from_json[0]))[0], convert(args.from_json[0], data, img)))
    with tempfile.TemporaryDirectory() as tmp:
        for src in args.inputs:
            js, png = export_with_aseprite(args.aseprite, src, tmp)
            data, img = load_sheet(js, png)
            sets.append((os.path.splitext(os.path.basename(src))[0], convert(src, data, img)))
    if not sets:
        ap.error("nothing to export")
    emit(sets, args.out)
    print(f"wrote {args.out}: {len(sets)} set(s)")


if __name__ == "__main__":
    main()
